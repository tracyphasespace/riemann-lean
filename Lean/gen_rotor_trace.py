#!/usr/bin/env python3
"""
Generate RotorTraceComputation.lean — eliminates rotorTrace_first1000_lt_bound_axiom.

Architecture:
1. Define primeList : List ℕ (the 1000 primes below 7920)
2. For each prime p, compute k_p = floor(t*log(p)/π) and sign_p = (-1)^k_p
   This is manual range reduction: cos(t*log(p)) = sign_p * cos(t*log(p) - k_p*π)
3. Define mkRotorTermReduced : ℚ → ℤ → Bool → Expr
4. Define rotorTraceCheckReduced that evaluates each term individually,
   extracts rational upper bounds, and sums them
5. ONE native_decide: rotorTraceCheckReduced allTerms (-5) cfg = true
6. Bridge lemmas connect Expr.eval to actual rotorTrace
"""

import math
import sys

def sieve(n):
    is_prime = [True] * (n + 1)
    is_prime[0] = is_prime[1] = False
    for i in range(2, int(n**0.5) + 1):
        if is_prime[i]:
            for j in range(i*i, n + 1, i):
                is_prime[j] = False
    return [i for i in range(n + 1) if is_prime[i]]

primes = sieve(7919)
assert len(primes) == 1000

# Compute range reduction data
t_rat = "565389/40000"  # = 14.134725
t_val = 565389 / 40000

terms = []
total = 0
for p in primes:
    arg = t_val * math.log(p)
    k = int(arg // math.pi)
    reduced = arg - k * math.pi
    assert 0 <= reduced < math.pi + 0.001, f"p={p}: reduced={reduced}"
    neg_sign = (k % 2 == 1)  # (-1)^k = -1 when k is odd
    term_val = math.log(p) * p**(-0.5) * math.cos(arg)
    total += term_val
    terms.append((p, k, neg_sign))

trace = 2 * total
assert trace < -5, f"Trace = {trace} is not < -5!"
print(f"# Trace value: {trace:.6f}, margin below -5: {-5 - trace:.6f}", file=sys.stderr)

# Format term list for Lean
def format_terms(terms, per_line=5):
    lines = []
    for i in range(0, len(terms), per_line):
        chunk = terms[i:i+per_line]
        items = []
        for (p, k, neg) in chunk:
            neg_str = "true" if neg else "false"
            items.append(f"({p}, {k}, {neg_str})")
        line = "  " + ", ".join(items)
        if i + per_line < len(terms):
            line += ","
        lines.append(line)
    return "\n".join(lines)

# Format prime list for Lean
def format_prime_list(primes, per_line=20):
    lines = []
    for i in range(0, len(primes), per_line):
        chunk = primes[i:i+per_line]
        line = "  " + ", ".join(str(p) for p in chunk)
        if i + per_line < len(primes):
            line += ","
        lines.append(line)
    return "\n".join(lines)

# Generate the Lean file
